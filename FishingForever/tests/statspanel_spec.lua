local helpers = require("helpers")

local POLE = 6256
local BLACKMOUTH = { id = 6358, name = "Oily Blackmouth" }
local ALBACORE = { id = 13754, name = "Raw Rainbow Fin Albacore" }

--- Logged in holding a pole, at skill 106 of 150 in Southshore, Hillsbrad
-- Foothills (level 20 to 30). `setup` runs before login, on the env.
local function loggedIn(setup)
    local ns, env = helpers.loadAddon()
    env.__mainHand = POLE
    env.__fishing = { rank = 106, maxRank = 150 }
    if setup then setup(env) end
    helpers.login(ns, env)
    return ns, env, ns.SkillBar.Frame(), ns.StatsPanel.Frame()
end

local function caught(env, fish, point)
    helpers.fire(env, "UNIT_SPELLCAST_CHANNEL_START", "player", "guid", 7620)
    env.__fishingLoot = true
    env.__loot = { fish or BLACKMOUTH }
    helpers.fire(env, "LOOT_OPENED")
    if point then
        env.__fishing.rank = env.__fishing.rank + 1
        helpers.fire(env, "SKILL_LINES_CHANGED")
    end
    helpers.fire(env, "LOOT_CLOSED")
    env.__fishingLoot = false
    env.__loot = {}
end

local function gotAway(env)
    helpers.fire(env, "UNIT_SPELLCAST_CHANNEL_START", "player", "guid", 7620)
    helpers.fire(env, "UI_ERROR_MESSAGE", 400, "Your fish got away!")
end

local function click(bar)
    bar.scripts.OnMouseDown(bar, "LeftButton")
    bar.scripts.OnMouseUp(bar, "LeftButton")
end

describe("the stats window", function()
    it("is hidden at first; a click on the bar opens it with the bar inside, across its top", function()
        local ns, env, bar, panel = loggedIn()
        assertFalse(panel:IsShown())
        click(bar)
        assertTrue(panel:IsShown())
        assertTrue(ns.db.skillBar.stats)
        assertEqual(panel, bar:GetParent())
        local point, relativeTo, relativePoint = bar:GetPoint(1)
        assertEqual("TOPLEFT", point)
        assertEqual(panel, relativeTo)
        assertEqual("TOPLEFT", relativePoint)
        assertTrue(bar.width > 220, "as wide as the window's inside")
        assertTrue(bar.frameLevel > panel:GetFrameLevel(), "over the window, not under it")
    end)

    it("gives the bar back to the screen where it was when it closes", function()
        local ns, env, bar, panel = loggedIn()
        click(bar)
        click(bar)
        assertFalse(panel:IsShown())
        assertTrue(bar:IsShown())
        assertEqual(env.UIParent, bar:GetParent())
        assertEqual(220, bar.width)
        local point, relativeTo, relativePoint, x, y = bar:GetPoint(1)
        assertEqual("CENTER", point)
        assertEqual(env.UIParent, relativeTo)
        assertEqual(0, x)
        assertEqual(-200, y)
    end)

    it("opens around the bar, so the bar stays where it was on the screen", function()
        local ns, env, bar, panel = loggedIn()
        bar.centerX, bar.top = 500, 400
        click(bar)
        local point, relativeTo, relativePoint, x, y = panel:GetPoint(1)
        assertEqual("TOP", point)
        assertEqual(env.UIParent, relativeTo)
        assertEqual("BOTTOMLEFT", relativePoint)
        assertEqual(500, x)
        local _, _, _, _, barY = bar:GetPoint(1)
        assertEqual(400, y + barY, "the window's top is as far above the bar's as the bar sits inside it")
    end)

    it("stays shut when the bar is dragged rather than clicked", function()
        local ns, env, bar, panel = loggedIn()
        bar.scripts.OnMouseDown(bar, "LeftButton")
        bar.scripts.OnDragStart(bar)
        bar.scripts.OnDragStop(bar)
        bar.scripts.OnMouseUp(bar, "LeftButton")
        assertFalse(panel:IsShown())
    end)

    it("goes with the bar when the pole comes off, and comes back with it", function()
        local ns, env, bar, panel = loggedIn()
        click(bar)
        env.__mainHand = 1161
        helpers.fire(env, "PLAYER_EQUIPMENT_CHANGED", 16)
        assertFalse(panel:IsShown())
        assertFalse(bar:IsShown())
        assertTrue(ns.db.skillBar.stats, "still wanted, once the pole is back")
        env.__mainHand = POLE
        helpers.fire(env, "PLAYER_EQUIPMENT_CHANGED", 16)
        assertTrue(panel:IsShown())
        assertEqual(panel, bar:GetParent())
    end)

    it("opens at login when it was open at logout", function()
        local ns, env, bar, panel = loggedIn()
        click(bar)
        local saved = env.FishingForeverDB
        local _, _, againBar, againPanel = loggedIn(function(e) e.FishingForeverDB = saved end)
        assertTrue(againPanel:IsShown())
        assertEqual(againPanel, againBar:GetParent())
    end)

    it("show the zone and its level, the totals, and a row for each ten skills, highest first", function()
        local ns, env, bar, panel = loggedIn(function(e) e.__fishing.rank = 108 end)
        caught(env, BLACKMOUTH)
        gotAway(env)
        caught(env, ALBACORE, true)
        caught(env, ALBACORE, true)
        caught(env, ALBACORE)
        click(bar)
        assertMatch("Hillsbrad Foothills", panel.zone.text)
        assertMatch("%(20%-30%)", panel.zone.text)
        assertEqual("4", panel.totals.caught.text)
        assertEqual("1", panel.totals.away.text)
        assertEqual("0", panel.totals.refused.text)
        assertEqual("80%", panel.totals.landed.text)
        assertEqual("110", panel.rows[1].skill.text)
        assertEqual("1", panel.rows[1].caught.text)
        assertEqual("100%", panel.rows[1].landed.text)
        assertEqual("108-109", panel.rows[2].skill.text)
        assertEqual("3", panel.rows[2].caught.text)
        assertEqual("1", panel.rows[2].away.text)
        assertEqual("75%", panel.rows[2].landed.text)
        assertFalse(panel.rows[3]:IsShown())
    end)

    it("say in a row's tooltip how many catches its points took, against the old rule", function()
        local ns, env, bar, panel = loggedIn()
        caught(env)
        caught(env, nil, true)
        caught(env, nil, true)
        click(bar)
        local row = panel.rows[1]
        row.scripts.OnEnter(row)
        local tooltip = table.concat({ env.GameTooltip.text or "", table.concat(env.GameTooltip.lines or {}, "\n") }, "\n")
        assertMatch("Hillsbrad Foothills, 106%-107", tooltip)
        assertMatch("2 points, 1.5 catches each", tooltip)
        assertMatch("the old rule: 2.3", tooltip)
    end)

    it("shows no share landed where the game refused every cast", function()
        local ns, env, bar, panel = loggedIn()
        helpers.fire(env, "UNIT_SPELLCAST_SENT", "player", "", "guid", 7620)
        helpers.fire(env, "UI_ERROR_MESSAGE", 300, "Skill not high enough")
        click(bar)
        assertEqual("1", panel.rows[1].refused.text)
        assertEqual("-", panel.rows[1].landed.text)
    end)

    it("show the zone without a level where the map has none", function()
        local ns, env, bar, panel = loggedIn(function(e) e.__map.levels = nil end)
        caught(env)
        click(bar)
        assertEqual("Hillsbrad Foothills", panel.zone.text)
    end)

    it("grey out what is nothing, and mark the skill you are at", function()
        local ns, env, bar, panel = loggedIn()
        caught(env)
        click(bar)
        local row = panel.rows[1]
        assertEqual(0.5, row.away.textColor[1], "a nought in grey")
        assertEqual(1, row.caught.textColor[2], "a count in full")
        assertEqual(0.82, row.skill.textColor[2], "the skill you are at, in gold")
    end)

    it("list the fish caught in the zone, the most caught first, each with its icon and its tooltip", function()
        local ns, env, bar, panel = loggedIn()
        caught(env, BLACKMOUTH)
        caught(env, ALBACORE)
        caught(env, ALBACORE)
        click(bar)
        local first, second = panel.fishRows[1], panel.fishRows[2]
        assertEqual("Raw Rainbow Fin Albacore", first.name.text)
        assertEqual("×2", first.count.text)
        assertEqual(133888, first.icon.texture)
        assertEqual("Oily Blackmouth", second.name.text)
        assertFalse(panel.fishRows[3] and panel.fishRows[3]:IsShown() or false)
        first.scripts.OnEnter(first)
        assertEqual(13754, env.GameTooltip.itemID)
    end)

    it("fit their height to what they list", function()
        local ns, env, bar, panel = loggedIn()
        caught(env, nil, true)
        click(bar)
        local short = panel:GetHeight()
        caught(env, nil, true)
        caught(env, ALBACORE, true)
        assertTrue(panel:GetHeight() > short)
    end)

    it("close with their red X, until the bar is clicked again", function()
        local ns, env, bar, panel = loggedIn()
        click(bar)
        panel.close.scripts.OnClick(panel.close)
        assertFalse(panel:IsShown())
        assertFalse(ns.db.skillBar.stats)
        click(bar)
        assertTrue(panel:IsShown())
    end)

    it("moves when dragged, by itself or by the bar, and the bar stays where it was left", function()
        local ns, env, bar, panel = loggedIn()
        click(bar)
        panel.scripts.OnDragStart(panel)
        assertTrue(panel.moving)
        bar.centerX, bar.centerY = 640, 300
        panel.scripts.OnDragStop(panel)
        assertFalse(panel.moving)
        assertEqual("CENTER", ns.db.skillBar.point)
        assertEqual("BOTTOMLEFT", ns.db.skillBar.relativePoint)
        assertEqual(640, ns.db.skillBar.x)
        assertEqual(300, ns.db.skillBar.y)

        bar.scripts.OnDragStart(bar)
        assertTrue(panel.moving, "the bar drags the window it is in")
        assertFalse(bar.moving == true)
        bar.scripts.OnDragStop(bar)

        click(bar)
        local point, _, relativePoint, x, y = bar:GetPoint(1)
        assertEqual("CENTER", point)
        assertEqual("BOTTOMLEFT", relativePoint)
        assertEqual(640, x)
        assertEqual(300, y)
    end)

    it("stays put while the bar is locked", function()
        local ns, env, bar, panel = loggedIn()
        ns.SkillBar.SetLocked(true)
        click(bar)
        panel.scripts.OnDragStart(panel)
        assertFalse(panel.moving == true)
    end)

    it("keeps the bar inside when its place is reset", function()
        local ns, env, bar, panel = loggedIn()
        click(bar)
        ns.SkillBar.ResetPosition()
        assertTrue(panel:IsShown())
        assertEqual(panel, bar:GetParent())
        assertEqual(0, ns.db.skillBar.x)
    end)

    it("keep up with each catch while open", function()
        local ns, env, bar, panel = loggedIn()
        click(bar)
        caught(env)
        assertEqual("1", panel.rows[1].caught.text)
    end)

    it("say so where nothing has been fished yet", function()
        local ns, env, bar, panel = loggedIn()
        click(bar)
        assertTrue(panel.empty:IsShown())
        assertMatch("Nothing fished here yet", panel.empty.text)
        assertFalse(panel.rows[1]:IsShown())
    end)

    it("turn to the other zones fished with the arrows, greyed while there are no others", function()
        local ns, env, bar, panel = loggedIn()
        caught(env)
        click(bar)
        assertFalse(panel.next:IsEnabled())
        env.__map = { id = 1436, name = "Westfall", levels = { 10, 20 } }
        env.__clock = env.__clock + 60
        caught(env)
        helpers.fire(env, "ZONE_CHANGED_NEW_AREA")
        assertTrue(panel.next:IsEnabled())
        assertMatch("Westfall", panel.zone.text)
        panel.next.scripts.OnClick(panel.next)
        assertMatch("Hillsbrad Foothills", panel.zone.text)
    end)

    it("turn from a zone not fished yet to the ones fished, and back", function()
        local ns, env, bar, panel = loggedIn()
        caught(env)
        env.__map = { id = 1437, name = "Wetlands", levels = { 20, 30 } }
        helpers.fire(env, "ZONE_CHANGED_NEW_AREA")
        click(bar)
        assertMatch("Wetlands", panel.zone.text)
        assertTrue(panel.next:IsEnabled())
        assertTrue(panel.prev:IsEnabled())
        panel.next.scripts.OnClick(panel.next)
        assertMatch("Hillsbrad Foothills", panel.zone.text)
        panel.prev.scripts.OnClick(panel.prev)
        assertMatch("Wetlands", panel.zone.text)
    end)

    it("show a skill's fish, places and bonus in a row's tooltip", function()
        local ns, env, bar, panel = loggedIn(function(e) e.__fishing.modifier = 25 end)
        caught(env, BLACKMOUTH)
        caught(env, ALBACORE)
        click(bar)
        local row = panel.rows[1]
        row.scripts.OnEnter(row)
        local tooltip = table.concat({ env.GameTooltip.text or "", table.concat(env.GameTooltip.lines or {}, "\n") }, "\n")
        assertMatch("Oily Blackmouth 1", tooltip)
        assertMatch("Raw Rainbow Fin Albacore 1", tooltip)
        assertMatch("Southshore 2", tooltip)
        assertMatch("%+25", tooltip)
    end)

    it("are shown and hidden with /ff stats too", function()
        local ns, env, bar, panel = loggedIn()
        helpers.command(env, "stats")
        assertTrue(panel:IsShown())
        helpers.command(env, "stats")
        assertFalse(panel:IsShown())
    end)
end)

describe("the summary, under the rows", function()
    --- The line of the summary with `label`, while it shows.
    local function stat(panel, label)
        for _, row in ipairs(panel.statRows) do
            if row:IsShown() and row.label.text == label then
                return row
            end
        end
    end

    local function tip(env, row)
        row.scripts.OnEnter(row)
        return table.concat({ env.GameTooltip.text or "", table.concat(env.GameTooltip.lines or {}, "\n") }, "\n")
    end

    it("gives the chance a catch brings a point, by the old rule, but not the count: the bar's fill is that", function()
        local ns, env, bar, panel = loggedIn()
        caught(env)
        caught(env)
        click(bar)
        assertNil(stat(panel, "Catches since your last point"))
        assertEqual(2, ns.Skill.Catches(), "still counted, for the bar")
        local chance = stat(panel, "Chance of a point per catch")
        assertEqual("1 in 2", chance.value.text)
        assertMatch("old game's rule", tip(env, chance))
    end)

    it("says when that chance is measured from your own points", function()
        local ns, env, bar, panel = loggedIn(function(e)
            e.FishingForeverDB = { skillUps = { [100] = { points = 6, catches = 18 } } }
        end)
        click(bar)
        local chance = stat(panel, "Chance of a point per catch")
        assertEqual("1 in 3", chance.value.text)
        assertMatch("6 of your points", tip(env, chance))
    end)

    it("says how many fish land here as the rows count them", function()
        local ns, env, bar, panel = loggedIn()
        for _ = 1, 9 do caught(env) end
        gotAway(env)
        click(bar)
        local landing = stat(panel, "Fish that land here")
        assertEqual("90%", landing.value.text)
        assertEqual(panel.totals.landed.text, landing.value.text, "the same share as the totals above")
        assertMatch("9 of 10 casts", tip(env, landing))
    end)

    it("leaves out the casts a point takes while it comes to the same as the catches", function()
        local ns, env, bar, panel = loggedIn()
        for _ = 1, 9 do caught(env) end
        gotAway(env)
        click(bar)
        assertEqual("1 in 2", stat(panel, "Chance of a point per catch").value.text)
        assertNil(stat(panel, "Casts a point takes here"), "2.2 catches over 90% is still about 2")
    end)

    it("says how many casts a point takes where so many fish get away that it is more", function()
        local ns, env, bar, panel = loggedIn()
        for _ = 1, 5 do caught(env) end
        for _ = 1, 5 do gotAway(env) end
        click(bar)
        assertEqual("1 in 2", stat(panel, "Chance of a point per catch").value.text)
        assertEqual("about 4", stat(panel, "Casts a point takes here").value.text)
    end)

    it("predicts nothing: no skill where every fish lands", function()
        local ns, env, bar, panel = loggedIn()
        for _ = 1, 9 do caught(env) end
        gotAway(env)
        click(bar)
        assertNil(stat(panel, "Every fish lands from"))
    end)

    it("counts toward the ten casts it needs before it says how many fish land here", function()
        local ns, env, bar, panel = loggedIn()
        caught(env)
        caught(env)
        gotAway(env)
        click(bar)
        assertEqual("3 of 10 casts", stat(panel, "Fish that land here").value.text)
    end)

    it("leaves out casts a point takes where every fish has landed", function()
        local ns, env, bar, panel = loggedIn()
        for _ = 1, 10 do caught(env) end
        click(bar)
        assertEqual("100%", stat(panel, "Fish that land here").value.text)
        assertNil(stat(panel, "Casts a point takes here"))
    end)

    it("says in red when the game refused a cast here", function()
        local ns, env, bar, panel = loggedIn()
        helpers.fire(env, "UNIT_SPELLCAST_SENT", "player", "", "guid", 7620)
        helpers.fire(env, "UI_ERROR_MESSAGE", 300, "Skill not high enough")
        click(bar)
        local low = stat(panel, "Too low to fish here")
        assertEqual("refused at 106", low.value.text)
        assertEqual(0.3, low.value.textColor[2])
        assertNil(stat(panel, "Fish that land here"))
    end)

    it("says in red when every fish of five casts here got away", function()
        local ns, env, bar, panel = loggedIn()
        for _ = 1, 5 do gotAway(env) end
        click(bar)
        local low = stat(panel, "Too low to land fish here")
        assertEqual("none of 5 landed", low.value.text)
        assertEqual(0.3, low.value.textColor[2])
        assertMatch("got away", tip(env, low))
        assertNil(stat(panel, "Fish that land here"))
    end)

    it("shows a lure's bonus", function()
        local ns, env, bar, panel = loggedIn(function(e) e.__fishing.modifier = 25 end)
        click(bar)
        local bonus = stat(panel, "Lure or gear bonus")
        assertEqual("+25", bonus.value.text)
        assertMatch("131", tip(env, bonus))
    end)

    it("says when the skill is at its cap, instead of counting toward a point", function()
        local ns, env, bar, panel = loggedIn(function(e) e.__fishing = { rank = 150, maxRank = 150 } end)
        click(bar)
        assertEqual("150/150", stat(panel, "Skill at its cap").value.text)
        assertNil(stat(panel, "Chance of a point per catch"))
    end)

    it("is headed Summary, between the rows and the fish", function()
        local ns, env, bar, panel = loggedIn()
        caught(env)
        click(bar)
        assertEqual("Summary", panel.summaryHead.label.text)
        local _, relativeTo = panel.summaryHead:GetPoint(1)
        assertEqual(panel.head, relativeTo)
        local _, fishRelativeTo = panel.fishHead:GetPoint(1)
        assertEqual(panel.summaryHead, fishRelativeTo)
    end)
end)

describe("the stats window on the options page", function()
    it("has a box there, under the bar's", function()
        local ns, env, bar, panel = loggedIn()
        ns.SettingsPanel.panel:Show()
        local box = ns.SettingsPanel.skillBarStats
        assertEqual("Open your fishing stats around it", box.fontStrings[1].text)
        box:SetChecked(true)
        box.scripts.OnClick(box)
        assertTrue(panel:IsShown())
    end)
end)
