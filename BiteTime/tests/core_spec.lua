local helpers = require("helpers")

describe("the saved settings", function()
    it("start from the defaults", function()
        local ns = helpers.loggedIn()
        assertTrue(ns.settings.buttons)
        assertTrue(ns.settings.center)
        assertEqual(80, ns.settings.share)
    end)

    it("keep what was saved", function()
        local ns = helpers.loggedIn(function(env)
            env.BiteTimeDB = { settings = { center = false, share = 65 } }
        end)
        assertFalse(ns.settings.center)
        assertEqual(65, ns.settings.share)
        assertTrue(ns.settings.buttons)
    end)

    it("survive a saved file with no settings in it", function()
        local ns = helpers.loggedIn(function(env) env.BiteTimeDB = "junk" end)
        assertTrue(ns.settings.buttons)
    end)
end)

describe("the slash command", function()
    it("says so when a command fails, since the game hides Lua errors by default", function()
        local ns, env = helpers.loggedIn()
        ns.RegisterCommand("boom", "Fail", function() error("kaboom") end)
        helpers.command(env, "boom")
        assertMatch("/bt boom failed: .*kaboom", helpers.printed(env))
    end)

    it("answers to /bt and /bitetime", function()
        local _, env = helpers.loggedIn()
        assertEqual("/bt", env.SLASH_BITETIME1)
        assertEqual("/bitetime", env.SLASH_BITETIME2)
    end)

    it("lists its commands for /bt help", function()
        local _, env = helpers.loggedIn()
        helpers.command(env, "help")
        local text = helpers.printed(env)
        assertMatch("/bt %- Open the settings page", text)
        assertMatch("/bt test %- ", text)
        assertMatch("/bt probe %- ", text)
    end)

    it("says so for a command it does not know, then lists the ones it does", function()
        local _, env = helpers.loggedIn()
        helpers.command(env, "bogus")
        local text = helpers.printed(env)
        assertMatch("Unknown command: bogus", text)
        assertMatch("/bt test", text)
    end)

    it("prints nothing at login", function()
        local _, env = helpers.loggedIn()
        assertEqual("", helpers.printed(env))
    end)
end)
