local helpers = require("helpers")

local STEALTH, STEALTH_R4, VANISH, PROWL, SHADOWMELD = 1784, 1787, 1856, 5215, 20580
local SPRINT, BLINK, HEARTHSTONE = 2983, 1953, 8690

--- Logged in, with every stealth the addon reports collected.
local function watching(setup)
    local ns, env = helpers.loggedIn(setup)
    return ns, env, helpers.reports(ns)
end

describe("an enemy player casting a stealth spell the client names", function()
    it("is reported with who they are and the spell", function()
        local ns, env, heard = watching()
        helpers.plateAdded(env, "nameplate1", env.__enemy("Sneaky", "ROGUE", 58, "Undead"))
        helpers.cast(env, "nameplate1", VANISH)
        assertEqual(1, #heard)
        assertEqual("Sneaky", heard[1].name)
        assertEqual("Rogue", heard[1].class)
        assertEqual("ROGUE", heard[1].classFile)
        assertEqual(58, heard[1].level)
        assertEqual("Undead", heard[1].race)
        assertEqual("Vanish", heard[1].spell)
        assertTrue(heard[1].confirmed)
    end)

    it("is reported for any rank", function()
        local ns, env, heard = watching()
        helpers.plateAdded(env, "nameplate1", env.__enemy("Sneaky"))
        helpers.cast(env, "nameplate1", STEALTH_R4)
        assertEqual("Stealth", heard[1] and heard[1].spell)
    end)

    it("covers Prowl and Shadowmeld too", function()
        local ns, env, heard = watching()
        helpers.plateAdded(env, "nameplate1", env.__enemy("Kitty", "DRUID"))
        helpers.plateAdded(env, "nameplate2", env.__enemy("Elf", "WARRIOR", 60, "Night Elf"))
        helpers.cast(env, "nameplate1", PROWL)
        helpers.cast(env, "nameplate2", SHADOWMELD)
        assertEqual(2, #heard)
        assertEqual("Prowl", heard[1].spell)
        assertEqual("Shadowmeld", heard[2].spell)
    end)

    -- WoW Forever is not vanilla: its own version of a spell may carry an id
    -- the classic list does not have.
    it("is recognised by the spell's name when the id is new", function()
        local ns, env, heard = watching(function(env)
            local known = env.C_Spell.GetSpellName
            env.C_Spell.GetSpellName = function(id) return id == 990001 and "Vanish" or known(id) end
        end)
        helpers.plateAdded(env, "nameplate1", env.__enemy("Sneaky"))
        helpers.cast(env, "nameplate1", 990001)
        assertEqual("Vanish", heard[1] and heard[1].spell)
    end)

    it("is reported even when they stay in sight", function()
        local ns, env, heard = watching()
        helpers.plateAdded(env, "nameplate1", env.__enemy("Sneaky"))
        helpers.cast(env, "nameplate1", STEALTH)
        assertEqual(1, #heard)
    end)

    it("is reported once, not again when their nameplate then goes", function()
        local ns, env, heard = watching()
        helpers.plateAdded(env, "nameplate1", env.__enemy("Sneaky"))
        helpers.cast(env, "nameplate1", VANISH)
        helpers.plateRemoved(env, "nameplate1")
        assertEqual(1, #heard)
    end)
end)

describe("an enemy player casting a spell the client names that is not stealth", function()
    it("is not reported, even when their nameplate goes straight after", function()
        local ns, env, heard = watching()
        helpers.plateAdded(env, "nameplate1", env.__enemy("Zippy", "MAGE"))
        helpers.cast(env, "nameplate1", BLINK)
        helpers.wait(env, 0.2)
        helpers.plateRemoved(env, "nameplate1")
        assertEqual(0, #heard)
    end)
end)

-- On WoW Forever the client hides which spell anyone but the player cast.
describe("an enemy player casting a spell the client hides", function()
    it("is reported when it was instant and their nameplate goes at once", function()
        local ns, env, heard = watching()
        helpers.plateAdded(env, "nameplate1", env.__enemy("Sneaky", "ROGUE", 60, "Gnome"))
        helpers.cast(env, "nameplate1", env.__secret())
        helpers.wait(env, 0.3)
        helpers.plateRemoved(env, "nameplate1")
        assertEqual(1, #heard)
        assertEqual("Sneaky", heard[1].name)
        assertEqual("Rogue", heard[1].class)
        assertNil(heard[1].spell)
        assertFalse(heard[1].confirmed)
    end)

    it("is not reported while they stay in sight", function()
        local ns, env, heard = watching()
        helpers.plateAdded(env, "nameplate1", env.__enemy("Sneaky"))
        helpers.cast(env, "nameplate1", env.__secret())
        assertEqual(0, #heard)
    end)

    it("is not reported when the nameplate goes well after the cast", function()
        local ns, env, heard = watching()
        helpers.plateAdded(env, "nameplate1", env.__enemy("Runner"))
        helpers.cast(env, "nameplate1", env.__secret())
        helpers.wait(env, 3)
        helpers.plateRemoved(env, "nameplate1")
        assertEqual(0, #heard)
    end)

    it("is not reported after a spell with a cast time, like a hearthstone", function()
        local ns, env, heard = watching()
        helpers.plateAdded(env, "nameplate1", env.__enemy("Homebound"))
        helpers.cast(env, "nameplate1", env.__secret(), 10)
        helpers.wait(env, 0.2)
        helpers.plateRemoved(env, "nameplate1")
        assertEqual(0, #heard)
    end)

    it("is reported for an instant after an interrupted cast", function()
        local ns, env, heard = watching()
        helpers.plateAdded(env, "nameplate1", env.__enemy("Kitty", "DRUID"))
        helpers.fire(env, "UNIT_SPELLCAST_START", "nameplate1", "Cast-1", env.__secret())
        helpers.wait(env, 1)
        helpers.fire(env, "UNIT_SPELLCAST_INTERRUPTED", "nameplate1", "Cast-1", env.__secret())
        helpers.cast(env, "nameplate1", env.__secret())
        helpers.plateRemoved(env, "nameplate1")
        assertEqual(1, #heard)
    end)

    it("is not reported when they died", function()
        local ns, env, heard = watching()
        local victim = env.__enemy("Unlucky")
        helpers.plateAdded(env, "nameplate1", victim)
        helpers.cast(env, "nameplate1", env.__secret())
        victim.dead = true
        helpers.plateRemoved(env, "nameplate1")
        assertEqual(0, #heard)
    end)

    it("is reported without issecretvalue, from a value that is no number", function()
        local ns, env, heard = watching(function(env)
            env.issecretvalue = nil
        end)
        helpers.plateAdded(env, "nameplate1", env.__enemy("Sneaky"))
        helpers.cast(env, "nameplate1", env.__secret())
        helpers.plateRemoved(env, "nameplate1")
        assertEqual(1, #heard)
    end)
end)

describe("a nameplate that goes with no cast before it", function()
    it("is someone walking out of range, and not reported", function()
        local ns, env, heard = watching()
        helpers.plateAdded(env, "nameplate1", env.__enemy("Walker"))
        helpers.wait(env, 5)
        helpers.plateRemoved(env, "nameplate1")
        assertEqual(0, #heard)
    end)
end)

describe("who counts", function()
    it("not a player on the player's own side", function()
        local ns, env, heard = watching()
        helpers.plateAdded(env, "nameplate1", env.__friend("Pal"))
        helpers.cast(env, "nameplate1", VANISH)
        helpers.cast(env, "nameplate1", env.__secret())
        helpers.plateRemoved(env, "nameplate1")
        assertEqual(0, #heard)
    end)

    it("not a creature", function()
        local ns, env, heard = watching()
        local defias = env.__enemy("Defias Footpad")
        defias.player = false
        helpers.plateAdded(env, "nameplate1", defias)
        helpers.cast(env, "nameplate1", STEALTH)
        assertEqual(0, #heard)
    end)

    it("not a unit that has no nameplate and is not the target", function()
        local ns, env, heard = watching()
        env.__units.party1 = env.__enemy("Duelist")
        helpers.cast(env, "party1", VANISH)
        assertEqual(0, #heard)
    end)

    it("the new player on a nameplate token the game has reused", function()
        local ns, env, heard = watching()
        helpers.plateAdded(env, "nameplate1", env.__enemy("First"))
        helpers.plateRemoved(env, "nameplate1")
        helpers.plateAdded(env, "nameplate1", env.__enemy("Second"))
        helpers.cast(env, "nameplate1", VANISH)
        assertEqual(1, #heard)
        assertEqual("Second", heard[1].name)
    end)

    it("players whose nameplates were already showing at login, as after a /reload", function()
        local ns, env = helpers.loadAddon()
        env.__units.nameplate3 = env.__enemy("Early")
        helpers.login(env)
        local heard = helpers.reports(ns)
        helpers.cast(env, "nameplate3", VANISH)
        assertEqual("Early", heard[1] and heard[1].name)
    end)

    it("no one once a nameplate has gone", function()
        local ns, env, heard = watching()
        helpers.plateAdded(env, "nameplate1", env.__enemy("Gone"))
        helpers.plateRemoved(env, "nameplate1")
        env.__units.nameplate1 = env.__enemy("Stale")
        helpers.cast(env, "nameplate1", VANISH)
        assertEqual(0, #heard)
    end)
end)

describe("the target", function()
    it("is watched like a nameplate, for a player who hides enemy nameplates", function()
        local ns, env, heard = watching()
        helpers.target(env, env.__enemy("Sneaky"))
        helpers.cast(env, "target", VANISH)
        assertEqual("Vanish", heard[1] and heard[1].spell)
    end)

    it("lost straight after a hidden instant cast is reported", function()
        local ns, env, heard = watching()
        helpers.target(env, env.__enemy("Sneaky"))
        helpers.cast(env, "target", env.__secret())
        helpers.wait(env, 0.2)
        helpers.target(env, nil)
        assertEqual(1, #heard)
        assertEqual("Sneaky", heard[1].name)
    end)

    it("swapped for someone else after a hidden instant cast is not reported", function()
        local ns, env, heard = watching()
        helpers.target(env, env.__enemy("Sneaky"))
        helpers.cast(env, "target", env.__secret())
        helpers.target(env, env.__enemy("Other"))
        assertEqual(0, #heard)
    end)

    it("then watches the new target", function()
        local ns, env, heard = watching()
        helpers.target(env, env.__enemy("First"))
        helpers.target(env, env.__enemy("Second"))
        helpers.cast(env, "target", VANISH)
        assertEqual("Second", heard[1] and heard[1].name)
    end)

    it("and its nameplate make one report, not two", function()
        local ns, env, heard = watching()
        local rogue = env.__enemy("Sneaky")
        helpers.plateAdded(env, "nameplate1", rogue)
        helpers.target(env, rogue)
        helpers.cast(env, "nameplate1", env.__secret())
        helpers.cast(env, "target", env.__secret())
        helpers.target(env, nil)
        helpers.plateRemoved(env, "nameplate1")
        assertEqual(1, #heard)
    end)
end)

describe("the same player again", function()
    it("is not reported within 10 seconds", function()
        local ns, env, heard = watching()
        helpers.plateAdded(env, "nameplate1", env.__enemy("Sneaky"))
        helpers.cast(env, "nameplate1", STEALTH)
        helpers.wait(env, 5)
        helpers.cast(env, "nameplate1", STEALTH)
        assertEqual(1, #heard)
    end)

    it("is reported after 10 seconds", function()
        local ns, env, heard = watching()
        helpers.plateAdded(env, "nameplate1", env.__enemy("Sneaky"))
        helpers.cast(env, "nameplate1", STEALTH)
        helpers.wait(env, 10)
        helpers.cast(env, "nameplate1", STEALTH)
        assertEqual(2, #heard)
    end)

    it("does not hold back someone else", function()
        local ns, env, heard = watching()
        helpers.plateAdded(env, "nameplate1", env.__enemy("Sneaky"))
        helpers.plateAdded(env, "nameplate2", env.__enemy("Sneakier"))
        helpers.cast(env, "nameplate1", STEALTH)
        helpers.cast(env, "nameplate2", STEALTH)
        assertEqual(2, #heard)
    end)
end)

describe("what the watcher has seen", function()
    it("counts casts whose spell the client named and those it hid", function()
        local ns, env = watching()
        helpers.plateAdded(env, "nameplate1", env.__enemy("Sneaky"))
        helpers.cast(env, "nameplate1", SPRINT)
        helpers.cast(env, "nameplate1", env.__secret())
        helpers.cast(env, "nameplate1", env.__secret())
        assertEqual(1, ns.Watcher.seen.named)
        assertEqual(2, ns.Watcher.seen.hidden)
    end)
end)
